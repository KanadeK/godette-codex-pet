"""Run artifact-level release checks that unit tests cannot replace."""

from __future__ import annotations

import argparse
import json
import shutil
from collections.abc import Callable
from pathlib import Path
from typing import Any

try:
    from .build_site import build_site
except ImportError:
    from build_site import build_site

from godette_pet.atlas import require_valid_pet
from godette_pet.diff import compare_pets
from godette_pet.package import build_release_archive
from godette_pet.render import render_plan
from godette_pet.trace import compile_frame_plan, coverage_report, load_trace

REQUIRED_FILES = (
    "README.md",
    "README.zh-CN.md",
    "LICENSE",
    "LICENSES/CC-BY-4.0.txt",
    "ASSET_LICENSE.md",
    "NOTICE.md",
    "SECURITY.md",
    "CONTRIBUTING.md",
    "CODE_OF_CONDUCT.md",
    "SUPPORT.md",
    "CITATION.cff",
    "action.yml",
    "docs/ARCHITECTURE.md",
    "docs/PETDIFF.md",
    "docs/TRACE_FORMAT.md",
    "docs/REPAIR.md",
    "docs/RESEARCH.md",
    "docs/RELEASE.md",
    "docs/media/godette-idle.gif",
    "pet/pet.json",
    "pet/spritesheet.webp",
    "pet/provenance.json",
    "artwork/hatch-run/qa/run-summary.json",
)
MARKER = ".godette-release-check"


def _reset_output(root: Path, output: Path) -> None:
    allowed = (root / "dist").resolve()
    if output != allowed and allowed not in output.parents:
        raise ValueError("release-check output must stay under repository dist/")
    if output.exists():
        if not output.is_dir():
            raise ValueError(f"release-check output is not a directory: {output}")
        marker = output / MARKER
        if not marker.is_file() and any(output.iterdir()):
            raise ValueError(
                f"refusing to replace unmarked directory {output}; "
                "choose an empty release-check output"
            )
        if marker.is_file():
            shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / MARKER).write_text(
        "generated by scripts/release_check.py\n",
        encoding="utf-8",
        newline="\n",
    )


def run_checks(root: Path, output: Path) -> dict[str, Any]:
    root = root.resolve()
    output = output.resolve()
    _reset_output(root, output)
    checks: list[dict[str, Any]] = []

    def check(name: str, operation: Callable[[], Any]) -> Any:
        try:
            detail = operation()
        except Exception as exc:
            checks.append({"name": name, "ok": False, "error": str(exc)})
            return None
        checks.append({"name": name, "ok": True, "detail": detail})
        return detail

    def required_files() -> dict[str, Any]:
        missing = [relative for relative in REQUIRED_FILES if not (root / relative).is_file()]
        if missing:
            raise ValueError("missing required files: " + ", ".join(missing))
        return {"count": len(REQUIRED_FILES)}

    check("required-files", required_files)
    pet_report = check("production-pet", lambda: require_valid_pet(root / "pet"))

    def fixture(name: str, *, all_states: bool, all_directions: bool) -> dict[str, Any]:
        events = load_trace(root / "examples" / name)
        report = coverage_report(events)
        if all_states and report["missing_states"]:
            raise ValueError("missing states: " + ", ".join(report["missing_states"]))
        if all_directions and report["missing_directions"]:
            raise ValueError("missing directions: " + ", ".join(report["missing_directions"]))
        return report

    bugfix_events = check(
        "all-state-fixture",
        lambda: fixture("bugfix-session.jsonl", all_states=True, all_directions=False),
    )
    check(
        "all-direction-fixture",
        lambda: fixture("direction-tour.jsonl", all_states=False, all_directions=True),
    )

    def replay_determinism() -> dict[str, Any]:
        if bugfix_events is None:
            raise ValueError("all-state fixture failed")
        events = load_trace(root / "examples" / "bugfix-session.jsonl")
        plan = compile_frame_plan(events, 10)
        first = render_plan(root / "pet", plan, output / "replay-a.gif")
        second = render_plan(root / "pet", plan, output / "replay-b.gif")
        if first["sha256"] != second["sha256"]:
            raise ValueError("two deterministic GIF renders have different SHA-256")
        render_plan(root / "pet", plan, output / "replay.webp")
        return {"sha256": first["sha256"], "frames": first["frames"]}

    check("replay-determinism", replay_determinism)
    check("petdiff-self", lambda: compare_pets(root / "pet", root / "pet", output / "petdiff"))

    def package_determinism() -> dict[str, Any]:
        first = build_release_archive(root, output / "package-a.zip", version="0.1.0")
        second = build_release_archive(root, output / "package-b.zip", version="0.1.0")
        if first["sha256"] != second["sha256"]:
            raise ValueError("two release archives have different SHA-256")
        return {"sha256": first["sha256"], "bytes": first["bytes"]}

    check("package-determinism", package_determinism)
    check("site-build", lambda: build_site(root, output / "site"))

    def visible_copy() -> dict[str, Any]:
        offenders: list[str] = []
        for name in ("index.html", "styles.css", "app.mjs"):
            text = (root / "web" / name).read_text(encoding="utf-8")
            if "\u2013" in text or "\u2014" in text:
                offenders.append(name)
        if offenders:
            raise ValueError("web files contain forbidden en/em dash: " + ", ".join(offenders))
        return {"checked": 3}

    check("web-copy", visible_copy)

    if pet_report is not None:
        official_hashes = {
            "57a00013441ba0b0adc48ecfcc7c97fe218554e1d709fdd19431e72aee62a629",
            "9a533893e86f83dbe4fa4f51c07b48a27374b056d3db200adfc1f20bb827e113",
            "88b49434a46ea2733b8215079a0bc89d4081eec81d442254f5188e298b35e7c0",
        }
        if pet_report["metrics"]["atlas_sha256"] in official_hashes:
            checks.append(
                {
                    "name": "derivative-art",
                    "ok": False,
                    "error": "production atlas unexpectedly matches an upstream reference",
                }
            )
        else:
            checks.append({"name": "derivative-art", "ok": True})

    report = {"ok": all(item["ok"] for item in checks), "checks": checks}
    (output / "release-check.json").write_text(
        json.dumps(report, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return report


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    output = args.output_dir or args.root / "dist" / "preflight"
    report = run_checks(args.root, output)
    if args.json:
        print(json.dumps(report, indent=2, sort_keys=True, ensure_ascii=False))
    else:
        for item in report["checks"]:
            print(("PASS" if item["ok"] else "FAIL") + " " + item["name"])
    raise SystemExit(0 if report["ok"] else 1)


if __name__ == "__main__":
    main()
