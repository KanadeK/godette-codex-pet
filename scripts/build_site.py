"""Build the dependency-free GitHub Pages artifact."""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

from godette_pet import __version__
from godette_pet.atlas import require_valid_pet

MARKER = ".godette-site-build"
STATIC_FILES = (
    "index.html",
    "styles.css",
    "app.mjs",
    "petdiff-core.mjs",
    "petdiff-worker.mjs",
)


def _prepare_output(root: Path, output: Path) -> None:
    if output in {root, root.parent, Path(output.anchor)}:
        raise ValueError("refusing to use a repository or filesystem root as site output")
    if output.exists():
        marker = output / MARKER
        if not marker.is_file():
            raise ValueError(
                f"refusing to replace unmarked directory {output}; choose an empty output"
            )
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / MARKER).write_text("generated by scripts/build_site.py\n", encoding="utf-8")


def build_site(root: Path, output: Path) -> dict[str, object]:
    root = root.resolve()
    output = output.resolve()
    pet_dir = root / "pet"
    validation = require_valid_pet(pet_dir)
    _prepare_output(root, output)

    web = root / "web"
    for relative in STATIC_FILES:
        shutil.copy2(web / relative, output / relative)

    assets = output / "assets"
    examples = output / "examples"
    assets.mkdir()
    examples.mkdir()
    shutil.copy2(pet_dir / "spritesheet.webp", assets / "spritesheet.webp")
    shutil.copy2(pet_dir / "pet.json", assets / "pet.json")
    for name in ("bugfix-session.jsonl", "direction-tour.jsonl"):
        shutil.copy2(root / "examples" / name, examples / name)

    metadata = {
        "schema_version": 1,
        "project": "godette-codex-pet",
        "version": __version__,
        "spriteVersionNumber": 2,
        "atlas_sha256": validation["metrics"]["atlas_sha256"],
        "required_cells": validation["metrics"]["required_cells"],
    }
    (assets / "build-metadata.json").write_text(
        json.dumps(metadata, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return {
        "ok": True,
        "output": str(output),
        "files": sorted(
            str(path.relative_to(output)).replace("\\", "/") for path in output.rglob("*")
        ),
        "metadata": metadata,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(build_site(args.root, args.output), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
